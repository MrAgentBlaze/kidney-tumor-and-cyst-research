DEFAULT_PRED_DIR = "results/stage1"
DEFAULT_LARGE_DIR = "data/kits23_large_processed"
DEFAULT_LOGS_DIR = "logs_stage1/logs"
DEFAULT_OUTPUT_DIR = "outputs/stage1_evaluation"

ROI_THRESHOLD = 0.1
MIN_COMPONENT_SIZE = 50
DILATION_FILTER_SIZE = 11
SPACING_MM = (1.99, 1.99, 1.99)  # isotropic Stage 1 preprocessed grid


def parse_args():
    parser = argparse.ArgumentParser(description="Evaluate Stage 1 ROI predictions.")
    parser.add_argument("--pred-dir", default=DEFAULT_PRED_DIR)
    parser.add_argument("--large-dir", default=DEFAULT_LARGE_DIR)
    parser.add_argument("--logs-dir", default=DEFAULT_LOGS_DIR)
    parser.add_argument("--output-dir", default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--threshold", type=float, default=ROI_THRESHOLD)
    parser.add_argument("--min-component-size", type=int, default=MIN_COMPONENT_SIZE)
    parser.add_argument("--dilation-size", type=int, default=DILATION_FILTER_SIZE)
    parser.add_argument("--max-cases", type=int, default=0,
                        help="For a quick test; 0 evaluates all cases.")
    parser.add_argument("--visualize-cases", type=int, default=5,
                        help="Number of best/worst/first cases to visualize.")
    parser.add_argument("--no-boundary-metrics", action="store_true",
                        help="Skip HD95 and ASSD to reduce runtime.")
    return parser.parse_args()


def load_trusted_torch_file(path: Path):
    # These prediction files are generated by this user's own pipeline.
    # weights_only=False is needed for compatible loading of saved objects.
    try:
        return torch.load(path, map_location="cpu", weights_only=False)
    except TypeError:  # compatibility with older PyTorch
        return torch.load(path, map_location="cpu")


def build_roi(prediction, target_shape, threshold, min_size, dilation_size):
    coords = prediction["coords"].detach().cpu().long().numpy()
    probabilities = prediction["logits"].detach().cpu().float()
    if probabilities.ndim != 2 or probabilities.shape[1] != 3:
        raise ValueError(f"Expected logits with shape (N, 3), got {tuple(probabilities.shape)}")
    if coords.ndim != 2 or coords.shape[1] != 3:
        raise ValueError(f"Expected coords with shape (N, 3), got {coords.shape}")
    if len(coords) != len(probabilities):
        raise ValueError("Number of coordinates and probability rows does not match.")

    valid = np.ones(len(coords), dtype=bool)
    for axis, length in enumerate(target_shape):
        valid &= (coords[:, axis] >= 0) & (coords[:, axis] < length)
    if not np.all(valid):
        warnings.warn(f"Ignoring {(~valid).sum()} out-of-bounds prediction coordinates.")

    coords = coords[valid]
    confidence = probabilities.max(dim=1).values.numpy()[valid]
    raw = np.zeros(target_shape, dtype=bool)
    selected = confidence >= threshold
    if selected.any():
        xyz = coords[selected]
        raw[xyz[:, 0], xyz[:, 1], xyz[:, 2]] = True

    # Match process_roi.py: MONAI RemoveSmallObjects, connectivity=1.
    cleaner = RemoveSmallObjects(
        min_size=min_size, connectivity=1, by_measure=False
    )
    clean_t = cleaner(torch.from_numpy(raw[None].astype(np.float32)))
    clean = clean_t.squeeze(0).cpu().numpy().astype(bool)

    # Match process_roi.py: label_components uses a full 3x3x3 structure.
    component_labels, n_components = ndi.label(
        clean, structure=np.ones((3, 3, 3), dtype=np.uint8)
    )

    # Match process_roi.py: MONAI elliptical ImageFilter applied separately
    # to each component; later components overwrite earlier ones on overlap.
    dilator = ImageFilter(filter="elliptical", filter_size=dilation_size)
    dilated_labels = np.zeros(target_shape, dtype=np.int32)
    for component_id in range(1, n_components + 1):
        component = component_labels == component_id
        expanded = dilator(torch.from_numpy(component[None].astype(np.float32)))
        expanded = expanded.squeeze(0).cpu().numpy() > 0
        dilated_labels[expanded] = component_id

    processed = dilated_labels > 0
    return raw, clean, processed, int(n_components)


def binary_metrics(pred, ref, spacing=SPACING_MM, boundary=True):
    pred = np.asarray(pred, dtype=bool)
    ref = np.asarray(ref, dtype=bool)
    tp = int(np.count_nonzero(pred & ref))
    fp = int(np.count_nonzero(pred & ~ref))
    fn = int(np.count_nonzero(~pred & ref))
    tn = int(np.count_nonzero(~pred & ~ref))

    denom_dice = 2 * tp + fp + fn
    denom_iou = tp + fp + fn
    dice = (2 * tp / denom_dice) if denom_dice else float("nan")
    iou = (tp / denom_iou) if denom_iou else float("nan")
    precision = tp / (tp + fp) if (tp + fp) else float("nan")
    recall = tp / (tp + fn) if (tp + fn) else float("nan")
    specificity = tn / (tn + fp) if (tn + fp) else float("nan")
    efficiency = recall  # same definition used in process_roi.py

    result = {
        "dice": dice, "iou": iou, "precision": precision,
        "recall": recall, "specificity": specificity,
        "efficiency": efficiency,
        "tp_voxels": tp, "fp_voxels": fp, "fn_voxels": fn,
        "tn_voxels": tn,
        "predicted_roi_voxels": int(pred.sum()),
        "reference_foreground_voxels": int(ref.sum()),
    }

    if boundary:
        if pred.any() and ref.any():
            # Surface voxels are foreground voxels adjacent to background.
            structure = ndi.generate_binary_structure(3, 1)
            pred_surface = pred & ~ndi.binary_erosion(pred, structure=structure, border_value=0)
            ref_surface = ref & ~ndi.binary_erosion(ref, structure=structure, border_value=0)
            dist_to_ref = ndi.distance_transform_edt(~ref_surface, sampling=spacing)
            dist_to_pred = ndi.distance_transform_edt(~pred_surface, sampling=spacing)
            distances = np.concatenate((
                dist_to_ref[pred_surface],
                dist_to_pred[ref_surface],
            ))
            result["hd95_mm"] = float(np.percentile(distances, 95))
            result["assd_mm"] = float(distances.mean())
        elif not pred.any() and not ref.any():
            result["hd95_mm"] = 0.0
            result["assd_mm"] = 0.0
        else:
            result["hd95_mm"] = float("nan")
            result["assd_mm"] = float("nan")
    return result


def safe_mean(values):
    arr = np.asarray([v for v in values if v is not None and np.isfinite(v)], dtype=float)
    return float(arr.mean()) if arr.size else float("nan")


def safe_std(values):
    arr = np.asarray([v for v in values if v is not None and np.isfinite(v)], dtype=float)
    return float(arr.std(ddof=1)) if arr.size > 1 else (0.0 if arr.size == 1 else float("nan"))


def evaluate_cases(args, output_dir):
    pred_dir = Path(args.pred_dir)
    large_dir = Path(args.large_dir)
    pred_files = sorted(pred_dir.glob("*.pt"))
    if not pred_files:
        raise FileNotFoundError(f"No .pt prediction files found in {pred_dir}")

    if args.max_cases > 0:
        pred_files = pred_files[:args.max_cases]

    rows = []
    visual_cache = {}
    print(f"\nEvaluating {len(pred_files)} prediction files...")
    for index, pred_path in enumerate(pred_files, start=1):
        case_id = pred_path.stem
        pkl_path = large_dir / f"{case_id}.pkl"
        if not pkl_path.exists():
            warnings.warn(f"Missing preprocessed reference: {pkl_path}; skipping {case_id}")
            continue

        try:
            prediction = load_trusted_torch_file(pred_path)
            with pkl_path.open("rb") as handle:
                processed_data = pickle.load(handle)

            if "coords" not in prediction or "logits" not in prediction:
                raise KeyError("Prediction must contain 'coords' and 'logits'.")
            if "label" not in processed_data:
                raise KeyError("Preprocessed .pkl must contain 'label'.")

            label = processed_data["label"]
            reference = np.asarray(label.detach().cpu()).squeeze() > 0
            image = np.asarray(processed_data["image"].detach().cpu()).squeeze()
            if reference.ndim != 3:
                raise ValueError(f"Expected 3D label, got shape {reference.shape}")
            if image.shape != reference.shape:
                raise ValueError(f"Image/label shape mismatch: {image.shape} vs {reference.shape}")

            raw, clean, roi, n_components = build_roi(
                prediction, reference.shape, args.threshold,
                args.min_component_size, args.dilation_size
            )
            if not np.any(reference):
                warnings.warn(f"{case_id}: reference foreground is empty.")

            raw_metrics = binary_metrics(
                raw, reference, boundary=not args.no_boundary_metrics
            )
            clean_metrics = binary_metrics(
                clean, reference, boundary=not args.no_boundary_metrics
            )
            final_metrics = binary_metrics(
                roi, reference, boundary=not args.no_boundary_metrics
            )

            row = {
                "case_id": case_id,
                "status": "ok",
                "n_components_before_dilation": n_components,
                **{f"raw_{k}": v for k, v in raw_metrics.items()},
                **{f"clean_{k}": v for k, v in clean_metrics.items()},
                **{f"final_{k}": v for k, v in final_metrics.items()},
            }
            rows.append(row)

            if len(visual_cache) < max(args.visualize_cases * 3, 3):
                visual_cache[case_id] = (image, reference, raw, roi, final_metrics["dice"])

            print(
                f"[{index:3d}/{len(pred_files)}] {case_id}: "
                f"Dice={final_metrics['dice']:.4f}, "
                f"IoU={final_metrics['iou']:.4f}, "
                f"Recall={final_metrics['recall']:.4f}, "
                f"components={n_components}"
            )
        except Exception as exc:
            warnings.warn(f"Failed {case_id}: {type(exc).__name__}: {exc}")
            rows.append({"case_id": case_id, "status": f"error: {exc}"})

    if not rows:
        raise RuntimeError("No cases could be evaluated. Check paths and data alignment.")

    csv_path = output_dir / "per_case_metrics.csv"
    keys = sorted({key for row in rows for key in row})
    with csv_path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=keys)
        writer.writeheader()
        writer.writerows(rows)

    successful = [r for r in rows if r.get("status") == "ok"]
    summary_rows = []
    metric_names = [
        "dice", "iou", "precision", "recall", "specificity", "efficiency",
        "hd95_mm", "assd_mm",
    ]
    for stage in ("raw", "clean", "final"):
        for metric in metric_names:
            column = f"{stage}_{metric}"
            vals = [r.get(column, float("nan")) for r in successful]
            summary_rows.append({
                "mask_stage": stage,
                "metric": metric,
                "n_cases": sum(np.isfinite(v) for v in vals if isinstance(v, (int, float))),
                "mean": safe_mean(vals),
                "std": safe_std(vals),
                "median": float(np.nanmedian(vals)) if np.isfinite(vals).any() else float("nan"),
                "minimum": float(np.nanmin(vals)) if np.isfinite(vals).any() else float("nan"),
                "maximum": float(np.nanmax(vals)) if np.isfinite(vals).any() else float("nan"),
            })

    with (output_dir / "aggregate_metrics.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(summary_rows[0]))
        writer.writeheader()
        writer.writerows(summary_rows)

    plot_case_metrics(successful, output_dir)
    plot_qualitative(visual_cache, successful, output_dir, args.visualize_cases)
    write_case_summary(successful, rows, output_dir, args.threshold)
    print(f"\nPer-case metrics: {csv_path}")
    print(f"Successfully evaluated: {len(successful)}/{len(pred_files)}")
    return successful


def plot_case_metrics(rows, output_dir):
    metrics = ["dice", "iou", "precision", "recall", "specificity", "hd95_mm", "assd_mm"]
    available = [m for m in metrics if any(np.isfinite(r.get(f"final_{m}", np.nan)) for r in rows)]
    if not available:
        return

    fig, axes = plt.subplots(2, 1, figsize=(15, 10), constrained_layout=True)
    case_ids = [r["case_id"] for r in rows]
    dice_vals = [r.get("final_dice", np.nan) for r in rows]
    axes[0].plot(range(len(rows)), dice_vals, linewidth=0.8)
    axes[0].set_title("Stage 1 ROI Dice by case")
    axes[0].set_xlabel("Case index (sorted by case ID)")
    axes[0].set_ylabel("Dice")
    axes[0].set_ylim(0, 1.02)
    axes[0].grid(alpha=0.25)

    plot_metrics = ["dice", "iou", "precision", "recall", "specificity"]
    data = [[r.get(f"final_{m}", np.nan) for r in rows] for m in plot_metrics]
    axes[1].boxplot(data, tick_labels=plot_metrics, showmeans=True)
    axes[1].set_title("Distribution of final post-processed ROI metrics")
    axes[1].set_ylabel("Score")
    axes[1].set_ylim(0, 1.05)
    axes[1].grid(axis="y", alpha=0.25)
    fig.savefig(output_dir / "roi_metric_distributions.png", dpi=180)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(12, 5), constrained_layout=True)
    for metric in ("dice", "iou", "precision", "recall"):
        vals = np.asarray([r.get(f"final_{metric}", np.nan) for r in rows], dtype=float)
        ax.hist(vals[np.isfinite(vals)], bins=30, alpha=0.45, label=metric)
    ax.set_title("Distribution of final ROI scores")
    ax.set_xlabel("Score")
    ax.set_ylabel("Number of cases")
    ax.legend()
    ax.grid(alpha=0.2)
    fig.savefig(output_dir / "roi_metric_histograms.png", dpi=180)
    plt.close(fig)


def plot_qualitative(cache, rows, output_dir, n_visuals):
    if not cache:
        return
    ranked = sorted(
        [(case_id, values[4]) for case_id, values in cache.items()
         if np.isfinite(values[4])],
        key=lambda item: item[1]
    )
    selected = []
    for case_id, _ in ranked[:max(1, n_visuals // 2)]:
        selected.append(case_id)
    for case_id, _ in ranked[-max(1, n_visuals - len(selected)):]:
        if case_id not in selected:
            selected.append(case_id)
    for case_id in list(cache):
        if len(selected) >= n_visuals:
            break
        if case_id not in selected:
            selected.append(case_id)

    for case_id in selected:
        image, reference, raw, roi, dice = cache[case_id]
        # Select the axis-0 slice containing the most reference foreground.
        slice_counts = reference.sum(axis=(1, 2))
        slice_idx = int(np.argmax(slice_counts))
        img_slice = image[slice_idx]
        ref_slice = reference[slice_idx]
        raw_slice = raw[slice_idx]
        roi_slice = roi[slice_idx]

        finite = img_slice[np.isfinite(img_slice)]
        lo, hi = (np.percentile(finite, [1, 99]) if finite.size else (0, 1))
        fig, axes = plt.subplots(1, 3, figsize=(15, 5), constrained_layout=True)
        panels = [
            ("Ground-truth ROI", None),
            ("Raw threshold ROI vs ground truth", raw_slice),
            ("Final ROI vs ground truth", roi_slice),
        ]
        for ax, (title, prediction_overlay) in zip(axes, panels):
            ax.imshow(img_slice, cmap="gray", vmin=lo, vmax=hi)
            if title == "Ground-truth ROI":
                ax.contour(ref_slice.astype(np.uint8), levels=[0.5], linewidths=0.9)
            else:
                if ref_slice.any():
                    ax.contour(ref_slice.astype(np.uint8), levels=[0.5],
                               linewidths=0.9, linestyles="dashed")
                if prediction_overlay is not None and prediction_overlay.any():
                    ax.contour(prediction_overlay.astype(np.uint8), levels=[0.5],
                               linewidths=0.9)
            ax.set_title(title)
            ax.axis("off")
        fig.suptitle(
            f"{case_id} | slice axis-0={slice_idx} | final ROI Dice={dice:.4f}"
        )
        fig.savefig(output_dir / f"qualitative_{case_id}.png", dpi=180)
        plt.close(fig)


def read_metrics_csv(path):
    rows = []
    with path.open("r", newline="") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            parsed = {}
            for key, value in row.items():
                if value is None or value == "":
                    parsed[key] = np.nan
                else:
                    try:
                        parsed[key] = float(value)
                    except (TypeError, ValueError):
                        parsed[key] = value
            rows.append(parsed)
    return rows


def safe_slug(text):
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", text)


def evaluate_logs(logs_dir, output_dir):
    logs_dir = Path(logs_dir)
    csv_files = sorted(logs_dir.rglob("metrics.csv")) if logs_dir.exists() else []
    if not csv_files:
        print(f"No metrics.csv files found under {logs_dir}; skipping training plots.")
        return

    log_summary = []
    combined_lr_fig, combined_lr_ax = plt.subplots(figsize=(13, 6), constrained_layout=True)
    combined_loss_fig, combined_loss_ax = plt.subplots(figsize=(13, 6), constrained_layout=True)
    lr_lines = 0
    loss_lines = 0

    for csv_path in csv_files:
        rows = read_metrics_csv(csv_path)
        if not rows:
            continue
        rel = str(csv_path.relative_to(logs_dir))
        slug = safe_slug(rel.replace("/", "_").replace("\\", "_").replace(".csv", ""))

        steps = np.asarray([r.get("step", np.nan) for r in rows], dtype=float)
        epochs = np.asarray([r.get("epoch", np.nan) for r in rows], dtype=float)
        lr = np.asarray([r.get("lr", np.nan) for r in rows], dtype=float)
        train_loss = np.asarray([r.get("loss/train_total", np.nan) for r in rows], dtype=float)
        val_loss = np.asarray([r.get("loss/val_total", np.nan) for r in rows], dtype=float)

        valid_lr = np.isfinite(steps) & np.isfinite(lr)
        if valid_lr.any():
            order = np.argsort(steps[valid_lr])
            x, y = steps[valid_lr][order], lr[valid_lr][order]
            fig, ax = plt.subplots(figsize=(11, 5), constrained_layout=True)
            ax.plot(x, y, linewidth=1.2)
            ax.set_title(f"Learning rate | {rel}")
            ax.set_xlabel("Optimizer/global step (logged step)")
            ax.set_ylabel("Learning rate")
            ax.grid(alpha=0.25)
            fig.savefig(output_dir / f"learning_rate_{slug}.png", dpi=170)
            plt.close(fig)
            combined_lr_ax.plot(x, y, linewidth=1.0, label=rel)
            lr_lines += 1

        fig, ax = plt.subplots(figsize=(11, 5), constrained_layout=True)
        train_valid = np.isfinite(steps) & np.isfinite(train_loss)
        val_valid = np.isfinite(steps) & np.isfinite(val_loss)
        if train_valid.any():
            ax.plot(steps[train_valid], train_loss[train_valid],
                    alpha=0.55, linewidth=0.8, label="Training total loss")
        if val_valid.any():
            ax.plot(steps[val_valid], val_loss[val_valid],
                    marker="o", linewidth=1.2, label="Validation total loss")
        ax.set_title(f"Training and validation loss | {rel}")
        ax.set_xlabel("Logged step")
        ax.set_ylabel("Total loss")
        ax.grid(alpha=0.25)
        if train_valid.any() or val_valid.any():
            ax.legend()
        fig.savefig(output_dir / f"loss_curves_{slug}.png", dpi=170)
        plt.close(fig)

        if train_valid.any():
            combined_loss_ax.plot(
                steps[train_valid], train_loss[train_valid],
                linewidth=0.8, alpha=0.6, label=f"{rel} train"
            )
            loss_lines += 1
        if val_valid.any():
            combined_loss_ax.plot(
                steps[val_valid], val_loss[val_valid],
                marker="o", linewidth=1.0, label=f"{rel} val"
            )
            loss_lines += 1

        finite_val = val_loss[np.isfinite(val_loss)]
        finite_train = train_loss[np.isfinite(train_loss)]
        log_summary.append({
            "log_file": rel,
            "rows": len(rows),
            "min_epoch": float(np.nanmin(epochs)) if np.isfinite(epochs).any() else np.nan,
            "max_epoch": float(np.nanmax(epochs)) if np.isfinite(epochs).any() else np.nan,
            "max_step": float(np.nanmax(steps)) if np.isfinite(steps).any() else np.nan,
            "min_learning_rate": float(np.nanmin(lr)) if np.isfinite(lr).any() else np.nan,
            "max_learning_rate": float(np.nanmax(lr)) if np.isfinite(lr).any() else np.nan,
            "min_logged_train_total_loss": float(finite_train.min()) if finite_train.size else np.nan,
            "min_logged_val_total_loss": float(finite_val.min()) if finite_val.size else np.nan,
        })

    if lr_lines:
        combined_lr_ax.set_title("Learning-rate schedules (each CSV is a separate logger session)")
        combined_lr_ax.set_xlabel("Logged step")
        combined_lr_ax.set_ylabel("Learning rate")
        combined_lr_ax.grid(alpha=0.25)
        combined_lr_ax.legend(fontsize=7, loc="best")
        combined_lr_fig.savefig(output_dir / "learning_rate_all_log_sessions.png", dpi=180)
    plt.close(combined_lr_fig)

    if loss_lines:
        combined_loss_ax.set_title("Loss curves (each CSV is a separate logger session)")
        combined_loss_ax.set_xlabel("Logged step")
        combined_loss_ax.set_ylabel("Loss")
        combined_loss_ax.grid(alpha=0.25)
        combined_loss_ax.legend(fontsize=6, loc="best")
        combined_loss_fig.savefig(output_dir / "loss_curves_all_log_sessions.png", dpi=180)
    plt.close(combined_loss_fig)

    if log_summary:
        with (output_dir / "training_log_summary.csv").open("w", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=list(log_summary[0]))
            writer.writeheader()
            writer.writerows(log_summary)
    print(f"Training log sessions plotted: {len(log_summary)}")


def write_case_summary(successful, all_rows, output_dir, threshold):
    metric_keys = ["final_dice", "final_iou", "final_precision",
                   "final_recall", "final_specificity", "final_hd95_mm",
                   "final_assd_mm"]
    lines = [
        "STAGE 1 ROI EVALUATION SUMMARY",
        "================================",
        f"Successfully evaluated cases: {len(successful)}",
        f"Failed/skipped cases: {len(all_rows) - len(successful)}",
        f"ROI threshold: {threshold}",
        f"Grid spacing used for boundary distances: {SPACING_MM} mm",
        "",
        "Final post-processed ROI metrics (mean +/- sample standard deviation):",
    ]
    for key in metric_keys:
        vals = np.asarray([r.get(key, np.nan) for r in successful], dtype=float)
        vals = vals[np.isfinite(vals)]
        if vals.size:
            sd = vals.std(ddof=1) if vals.size > 1 else 0.0
            lines.append(f"  {key}: {vals.mean():.6f} +/- {sd:.6f} (n={vals.size})")
    lines += [
        "",
        "Interpretation:",
        "- These are Stage 1 ROI-localization metrics, with all non-background",
        "  reference labels combined into one foreground mask.",
        "- Efficiency is identical to recall: TP / (TP + FN).",
        "- HD95 and ASSD are in millimetres, calculated on the isotropic 1.99-mm grid.",
        "- Do not report these ROI metrics as class-wise kidney, tumor, or cyst",
        "  segmentation scores.",
        "- The training-log CSV files are plotted separately because they represent",
        "  separate logger sessions; do not combine them as one continuous run.",
        "",
        "Important: this script evaluates predictions against labels stored in",
        "data/kits23_large_processed. Confirm that this is the intended evaluation",
        "split and not a training-only split before describing results as held-out",
        "test performance.",
    ]
    (output_dir / "report_summary.txt").write_text("\n".join(lines), encoding="utf-8")


