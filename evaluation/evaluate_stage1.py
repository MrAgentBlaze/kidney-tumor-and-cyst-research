#!/usr/bin/env python3
"""
Stage 1 ROI evaluation for the KiTS23 sparse-voxel pipeline.

Run from the project root:
    python evaluate_stage1.py

Optional:
    python evaluate_stage1.py --pred-dir results/stage1 \
        --large-dir data/kits23_large_processed \
        --logs-dir logs_stage1/logs \
        --output-dir outputs/stage1_evaluation

The prediction coordinates and the preprocessed labels are evaluated on the
same 1.99-mm grid. This avoids an unnecessary resampling round trip to the
original NIfTI grid. The post-processing mirrors process_roi.py:
threshold=max(channel probabilities) >= 0.1, remove components < 50 voxels,
label components with 26-connectivity, then apply MONAI's elliptical
ImageFilter (size 11) independently to each component.

This evaluates Stage 1 ROI localization (all foreground labels combined),
NOT kidney/tumor/cyst class-wise segmentation.
"""

